CREATE TABLE IF NOT EXISTS users (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(50)  NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    fullname      VARCHAR(150) NOT NULL DEFAULT '',
    role          VARCHAR(10)  NOT NULL DEFAULT 'staff' CHECK (role IN ('admin', 'staff')),
    is_active     SMALLINT     NOT NULL DEFAULT 1,
    last_login    TIMESTAMP    NULL,
    created_at    TIMESTAMP    NOT NULL DEFAULT NOW(),
    updated_at    TIMESTAMP    NOT NULL DEFAULT NOW()
);
-- ชื่อผู้ใช้ไม่สนตัวพิมพ์เล็ก/ใหญ่ (เหมือน MySQL เดิม)
CREATE UNIQUE INDEX IF NOT EXISTS users_username_lower_uq ON users (lower(username));

CREATE TABLE IF NOT EXISTS links (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type          VARCHAR(10)   NOT NULL DEFAULT 'website' CHECK (type IN ('website', 'system', 'document')),
    name          VARCHAR(255)  NOT NULL,
    url           VARCHAR(2048) NULL,
    is_visible    SMALLINT      NOT NULL DEFAULT 1,
    file_original VARCHAR(255)  NULL,
    file_stored   VARCHAR(100)  NULL,
    file_mime     VARCHAR(150)  NULL,
    file_size     BIGINT        NULL,
    file_visible  SMALLINT      NOT NULL DEFAULT 1,
    created_by    INTEGER       NULL,
    updated_by    INTEGER       NULL,
    created_at    TIMESTAMP     NOT NULL DEFAULT NOW(),
    updated_at    TIMESTAMP     NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_links_name    ON links (name);
CREATE INDEX IF NOT EXISTS idx_links_visible ON links (is_visible);

-- เนื้อไฟล์แนบ (แยกตารางเพื่อไม่ให้หน้ารายการโหลดข้อมูลไฟล์โดยไม่จำเป็น)
CREATE TABLE IF NOT EXISTS link_files (
    link_id    INTEGER   PRIMARY KEY REFERENCES links (id) ON DELETE CASCADE,
    data       BYTEA     NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS favorites (
    user_id    INTEGER   NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    link_id    INTEGER   NOT NULL REFERENCES links (id) ON DELETE CASCADE,
    created_at TIMESTAMP NOT NULL DEFAULT NOW(),
    PRIMARY KEY (user_id, link_id)
);

-- updated_at อัตโนมัติ (แทน ON UPDATE CURRENT_TIMESTAMP ของ MySQL)
CREATE OR REPLACE FUNCTION udpt_touch_updated_at() RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at := NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_users_updated ON users;
CREATE TRIGGER trg_users_updated BEFORE UPDATE ON users
    FOR EACH ROW EXECUTE FUNCTION udpt_touch_updated_at();

DROP TRIGGER IF EXISTS trg_links_updated ON links;
CREATE TRIGGER trg_links_updated BEFORE UPDATE ON links
    FOR EACH ROW EXECUTE FUNCTION udpt_touch_updated_at();
